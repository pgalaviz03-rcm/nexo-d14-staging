#!/bin/sh
set -eu
: "${NEXO_APP_DB_PASSWORD:?Define NEXO_APP_DB_PASSWORD}"
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" -v app_pwd="$NEXO_APP_DB_PASSWORD" <<'SQL'
SELECT format('CREATE ROLE nexo_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS PASSWORD %L', :'app_pwd') WHERE NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='nexo_app') \gexec
GRANT CONNECT ON DATABASE nexo TO nexo_app;
SQL
