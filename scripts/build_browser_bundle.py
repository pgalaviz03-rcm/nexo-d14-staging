"""Build the single browser module asset; run before packaging."""
from pathlib import Path
import hashlib,re
ROOT=Path(__file__).resolve().parents[1]
FILES=['experience.js', 'reviews.js', 'reports.js', 'pulse.js', 'platform.js', 'apify_settings.js', 'settings.js', 'workbench.js', 'actors.js', 'networks.js', 'account_audit.js', 'workbooks.js', 'evidence_cards.js', 'library.js', 'fidelity_team.js', 'fidelity.js', 'continuity.js', 'alerts.js', 'explorer.js', 'briefing.js', 'delivery.js', 'refresh.js']
def build():
    script='/* NEXO browser modules: generated by scripts/build_browser_bundle.py. */\n'+''.join('\n/* '+name+' */\n'+(ROOT/'static'/name).read_text(encoding='utf8').replace('\r\n','\n')+'\n;' for name in FILES)
    (ROOT/'static/nexo-modules.js').write_text(script,encoding='utf8',newline='\n')
    digest=hashlib.sha256(script.encode()).hexdigest()[:16]
    p=ROOT/'static/index.html';html=p.read_text(encoding='utf8')
    html=re.sub(r'/assets/nexo-modules.js\?v=[a-f0-9]+','/assets/nexo-modules.js?v='+digest,html)
    p.write_text(html,encoding='utf8')
    return digest
if __name__=='__main__':print(build())
